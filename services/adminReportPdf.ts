import { Platform } from 'react-native';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';

type Report = {
  id: string;
  title: string;
  period: string;
  generated: string;
  rows: Record<string, unknown>[];
  metrics: { label: string; value: string }[];
  notes: string[];
  count: number;
};

const reportTemplate = { template: String.raw`<!doctype html><html><head><meta charset="utf-8"><style>
@page{size:A4;margin:16mm}*{box-sizing:border-box}body{font:10px Arial,Helvetica,sans-serif;color:#26372d;line-height:1.45}
header{display:flex;justify-content:space-between;border-bottom:3px solid #55765d;padding-bottom:12px;margin-bottom:18px}
header strong{font-size:22px;letter-spacing:-.5px}header small{display:block;color:#727c70;font-size:9px;letter-spacing:1px;margin-top:3px}
h1{font-size:23px;margin:0 0 5px}.muted{color:#727c70}.meta{display:flex;justify-content:space-between;gap:12px;background:#f3f5ef;padding:11px;border-radius:8px;margin:14px 0}
.metrics{display:flex;flex-wrap:wrap;gap:8px;margin:14px 0 20px}[data-metric]{flex:1;min-width:115px;background:#f3f5ef;border:1px solid #e5e9e0;padding:10px;border-radius:8px}
[data-metric] span{display:block;color:#727c70;font-size:8px;text-transform:uppercase;letter-spacing:.5px}[data-metric] strong{display:block;font-size:16px;margin-top:5px}
h2{font-size:13px;margin:18px 0 8px}ul{padding-left:17px;color:#727c70}
table{width:100%;border-collapse:collapse;font-size:8px;table-layout:fixed;word-break:break-word}th{background:#26372d;color:white;text-align:left;padding:8px;text-transform:capitalize}
td{border-bottom:1px solid #e5e9e0;padding:7px;vertical-align:top}tr:nth-child(even) td{background:#fafbf8}
footer{position:fixed;bottom:-9mm;left:0;right:0;border-top:1px solid #e5e9e0;padding-top:6px;color:#899187;font-size:8px;display:flex;justify-content:space-between}
</style></head><body>
<header><div><strong>BunaLens</strong><small>COFFEE INTELLIGENCE PLATFORM · JIMMA, ETHIOPIA</small></div><b>ADMINISTRATIVE REPORT</b></header>
<h1>__TITLE__</h1><div class="muted">__PERIOD__</div>
<div class="meta"><div><b>Report reference</b><br>__REFERENCE__</div><div><b>Generated by</b><br>__ADMIN__</div><div><b>Generated at</b><br>__GENERATED__</div></div>
<h2>Executive summary</h2><div class="metrics">__METRICS__</div>
__NOTES__
<h2>Records represented (__COUNT__)</h2>__TABLE__ __TRUNCATION__
<footer><span>CONFIDENTIAL · BunaLens administrative information</span><span>__REFERENCE__</span></footer>
</body></html>` };
const escape = (value: unknown) => String(value ?? '—').replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char] || char));
const dateText = (value: string) => new Date(value).toLocaleString();

function makeHtml(report: Report, admin: string) {
  const columns = report.rows.length ? Object.keys(report.rows[0]!).slice(0, 8) : [];
  const table = columns.length
    ? '<table><thead><tr>' + columns.map(column => '<th>' + escape(column.replaceAll('_', ' ')) + '</th>').join('') + '</tr></thead><tbody>' +
      report.rows.slice(0, 5000).map(row => '<tr>' + columns.map(column => '<td>' + escape(row[column]) + '</td>').join('') + '</tr>').join('') + '</tbody></table>'
    : '<p>No matching records were found.</p>';
  const metrics = report.metrics.map(metric => '<div data-metric="1"><span>' + escape(metric.label) + '</span><strong>' + escape(metric.value) + '</strong></div>').join('');
  const notes = report.notes.map(note => '<li>' + escape(note) + '</li>').join('');
  let html = reportTemplate.template;
  const replacements: Record<string, string> = {
    TITLE: escape(report.title),
    PERIOD: escape(report.period),
    REFERENCE: escape(report.id),
    ADMIN: escape(admin),
    GENERATED: escape(dateText(report.generated)),
    METRICS: metrics,
    NOTES: notes,
    COUNT: report.count.toLocaleString(),
    TABLE: table,
    TRUNCATION: report.rows.length > 5000 ? '<p>Detail is limited to the first 5,000 rows; summary uses all ' + report.count.toLocaleString() + ' source records.</p>' : '',
  };
  for (const [key, value] of Object.entries(replacements)) html = html.replaceAll('__' + key + '__', value);
  return html;
}

export async function exportAdminReportPdf(report: Report, admin: string): Promise<'print' | 'share'> {
  const html = makeHtml(report, admin);
  if (Platform.OS === 'web') {
    await Print.printAsync({ html });
    return 'print';
  }
  const file = await Print.printToFileAsync({ html });
  if (await Sharing.isAvailableAsync()) {
    await Sharing.shareAsync(file.uri, { mimeType: 'application/pdf', dialogTitle: 'BunaLens ' + report.title });
    return 'share';
  }
  await Print.printAsync({ html });
  return 'print';
}
